// Writes ABIs + recorded MST Testnet addresses into web3/src/generated/deployment.js
// so the frontend imports one module. Run after `hardhat compile` and after deploy.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const names = ["ChallengeRegistry", "SubmissionRegistry", "RewardVault"];

const abis = {};
for (const n of names) {
  const artifact = join(root, "artifacts/contracts", `${n}.sol`, `${n}.json`);
  if (!existsSync(artifact)) throw new Error(`Missing ${artifact}; run "npx hardhat compile" first.`);
  abis[n] = JSON.parse(readFileSync(artifact, "utf8")).abi;
}

const deploymentFile = join(root, "deployments", process.env.DEPLOYMENT_FILE || "mstTestnet.json");
const recorded = existsSync(deploymentFile) ? JSON.parse(readFileSync(deploymentFile, "utf8")) : null;

const out = {
  network: "mstTestnet",
  chainId: 91562037,
  addresses: recorded?.addresses ?? { ChallengeRegistry: null, SubmissionRegistry: null, RewardVault: null },
  deployedAt: recorded?.deployedAt ?? null,
  deployer: recorded?.deployer ?? null,
  abis,
};

const target = join(root, "web3/src/generated/deployment.js");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `// AUTO-GENERATED by scripts/export-deployment.mjs. Do not edit.\nexport const deployment = ${JSON.stringify(out, null, 2)};\n`);
for (const n of names) writeFileSync(join(root, "web3/src/generated", `${n}.abi.json`), JSON.stringify(abis[n], null, 2) + "\n");
console.log(`Exported ABIs${recorded ? ` and addresses from deployments/${process.env.DEPLOYMENT_FILE || "mstTestnet.json"}` : " (no deployment recorded yet)"} -> web3/src/generated/`);
